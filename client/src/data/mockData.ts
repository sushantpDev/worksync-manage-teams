export function getUserById(id: string): User | undefined {
  return users.find((u) => u.id === id)
}

export function getProjectById(id: string): Project | undefined {
  return projects.find((p) => p.id === id)
}

export function getTasksByProjectId(projectId: string): Task[] {
  return tasks.filter((t) => t.projectId === projectId)
}

export function getTasksByStatus(status: Task['status']): Task[] {
  return tasks.filter((t) => t.status === status)
}

export function getProjectMembers(project: Project): User[] {
  return project.memberIds.map((id) => getUserById(id)).filter(Boolean) as User[]
}
